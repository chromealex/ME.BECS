using System;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace ME.BECS.SourceGenerator;

// Physical provenance only. File content is never evidence that a loaded IL
// summary is current: validation uses compiled declarations and method bodies.
[Generator(LanguageNames.CSharp)]
public sealed class SourceTypeMapGenerator : IIncrementalGenerator {
    public void Initialize(IncrementalGeneratorInitializationContext context) {
        var rows = context.SyntaxProvider.CreateSyntaxProvider(
            static (node, _) => node is BaseTypeDeclarationSyntax or DelegateDeclarationSyntax,
            static (syntax, cancellation) => {
                var type = syntax.SemanticModel.GetDeclaredSymbol(syntax.Node, cancellation) as INamedTypeSymbol;
                if (type == null) { return null; }
                var path = PortablePath(syntax.Node.SyntaxTree.FilePath);
                if (path == null) { return null; }
                return MetadataName(type) + "\t" + path;
            }).Where(static row => row != null).Collect();
        var enabled = context.CompilationProvider.Select(static (compilation, _) =>
            compilation.GetTypeByMetadataName("ME.BECS.IComponentBase") != null);
        context.RegisterSourceOutput(rows.Combine(enabled), static (output, input) => {
            if (input.Right == true) { Emit(output, input.Left); }
        });
    }

    private static string MetadataName(INamedTypeSymbol type) {
        if (type.ContainingType != null) { return MetadataName(type.ContainingType) + "+" + type.MetadataName; }
        return type.ContainingNamespace.IsGlobalNamespace == true ? type.MetadataName : type.ContainingNamespace.ToDisplayString() + "." + type.MetadataName;
    }

    internal static string? PortablePath(string path) {
        if (string.IsNullOrEmpty(path) == true) { return null; }
        path = path.Replace('\\', '/');
        if (path.StartsWith("./", StringComparison.Ordinal) == true) { path = path.Substring(2); }
        foreach (var root in new[] { "Assets/", "Packages/", "Library/PackageCache/" }) {
            if (path.StartsWith(root, StringComparison.Ordinal) == true) { return path; }
            var index = path.IndexOf("/" + root, StringComparison.Ordinal);
            if (index >= 0) { return path.Substring(index + 1); }
        }
        // Unknown/external source is deliberately unmapped, never made relative
        // to an agent machine's current working directory.
        return null;
    }

    private static void Emit(SourceProductionContext context, ImmutableArray<string?> rows) {
        var data = "v1\n" + string.Join("\n", rows.Where(static row => row != null)
            .Distinct(StringComparer.Ordinal).OrderBy(static row => row, StringComparer.Ordinal));
        var source = "// <auto-generated/>\n[assembly: global::System.Reflection.AssemblyMetadataAttribute(\"ME.BECS.SourceTypeMap.v1\", " +
            Microsoft.CodeAnalysis.CSharp.SymbolDisplay.FormatLiteral(data, true) + ")]\n";
        context.AddSource("ME.BECS.SourceTypeMap.g.cs", SourceText.From(source, Encoding.UTF8));
    }
}
