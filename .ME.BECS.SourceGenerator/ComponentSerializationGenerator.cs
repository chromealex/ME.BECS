using System;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace ME.BECS.SourceGenerator;

// Owner-local assembly attributes need neither partial declarations nor an IL export.
[Generator(LanguageNames.CSharp)]
public sealed class ComponentSerializationGenerator : IIncrementalGenerator {
    private const string AttributeName = "UnityEngine.MakeSerializableAttribute";

    public void Initialize(IncrementalGeneratorInitializationContext context) {
        var types = context.SyntaxProvider.CreateSyntaxProvider(
            static (node, _) => node is TypeDeclarationSyntax declaration && declaration.BaseList != null,
            static (syntax, cancellation) => Describe(
                syntax.SemanticModel.GetDeclaredSymbol(syntax.Node, cancellation) as INamedTypeSymbol,
                syntax.SemanticModel.Compilation))
            .Where(static name => name != null).Collect();
        context.RegisterSourceOutput(types, static (output, names) => {
            var declarations = names.Where(static name => name != null).Distinct(StringComparer.Ordinal)
                .OrderBy(static name => name, StringComparer.Ordinal).ToArray();
            if (declarations.Length == 0) { return; }
            var source = new StringBuilder("// <auto-generated/>\n");
            foreach (var name in declarations) {
                source.Append("[assembly: global::UnityEngine.MakeSerializableAttribute(typeof(")
                    .Append(name).AppendLine("))]");
            }
            output.AddSource("ME.BECS.ComponentSerialization.g.cs", SourceText.From(source.ToString(), Encoding.UTF8));
        });
    }

    private static string? Describe(INamedTypeSymbol? type, Compilation compilation) {
        if (compilation.GetTypeByMetadataName(AttributeName) == null || type == null ||
            // Unity's attribute constructor rejects value types at domain reload.
            type.TypeKind != TypeKind.Class ||
            type.IsAbstract == true || type.IsRefLikeType == true ||
            compilation.IsSymbolAccessibleWithin(type, compilation.Assembly) == false) { return null; }
        if (type.AllInterfaces.Any(static contract => contract.ToDisplayString() is
                "ME.BECS.IComponentBase" or "ME.BECS.Views.IViewModule") == false) { return null; }
        // Open definitions are not concrete SerializeReference values.
        for (var owner = type; owner != null; owner = owner.ContainingType) {
            if (owner.Arity != 0) { return null; }
        }
        if (type.GetAttributes().Any(static attribute => attribute.AttributeClass?.ToDisplayString() ==
                "System.SerializableAttribute") == true ||
            compilation.Assembly.GetAttributes().Any(attribute => attribute.AttributeClass?.ToDisplayString() == AttributeName &&
                attribute.ConstructorArguments.Length == 1 &&
                SymbolEqualityComparer.Default.Equals(attribute.ConstructorArguments[0].Value as ITypeSymbol, type)) == true) { return null; }
        return type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
    }
}
